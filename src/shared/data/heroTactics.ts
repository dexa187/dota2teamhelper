export const HERO_TACTICS: Record<string, HeroTactics> = Object.fromEntries(
  Object.entries(RAW_HERO_SPECS).map(([heroName, spec]) => {
    const [posScores, aliases, archetype, laneTraits, rawThreats, core, late, opts] = spec;
    const baseItems = START_BY_ARCHETYPE[archetype];
    const coreItems: HeroCoreItems = {
      starting: opts?.starting ?? baseItems.starting,
      early: opts?.early ?? baseItems.early,
      core,
      late,
      turboReplace: opts?.turboReplace,
      shardPriority: opts?.shardPriority ?? 'medium',
    };
    return [
      heroName,
      {
        posScores,
        aliases,
        archetype,
        laneTraits,
        threats: th(rawThreats),
        coreItems,
      },
    ];
  })
);

export function synthesizeFallbackHeroTactics(hero: HeroBaseData): HeroTactics {
  const isSupport = hero.roles.includes('Support') && !hero.roles.includes('Carry');
  const isCarry = hero.roles.includes('Carry');
  const isInitiator = hero.roles.includes('Initiator') || hero.roles.includes('Durable');

  let archetype: HeroArchetype = 'tempo_mid';
  let posScores: [number, number, number, number, number] = [4, 7, 5, 3, 2];

  if (isCarry && hero.primaryAttr === 'agi') {
    archetype = 'right_click_carry';
    posScores = [9, 4, 2, 1, 0];
  } else if (isInitiator) {
    archetype = 'initiator_offlaner';
    posScores = [2, 3, 9, 4, 1];
  } else if (isSupport) {
    archetype = 'lane_support';
    posScores = [0, 1, 2, 7, 8];
  }

  const base = START_BY_ARCHETYPE[archetype];
  return {
    posScores,
    aliases: [hero.localizedName.toLowerCase()],
    archetype,
    laneTraits: {
      laneStrength: 2,
      hasStun: hero.roles.includes('Disabler'),
      hasPush: hero.roles.includes('Pusher'),
      hasHarass: hero.attackType === 'Ranged',
    },
    threats: [],
    coreItems: {
      starting: base.starting,
      early: base.early,
      core: isSupport ? ['force_staff', 'glimmer_cape', 'aghanims_shard'] : ['black_king_bar', 'blink', 'ultimate_scepter'],
      late: isSupport ? ['aeon_disk', 'wind_waker'] : ['assault', 'heart'],
      shardPriority: 'medium',
    },
  };
}

export function buildHeroCatalog(snapshot: OpenDotaSnapshot): HeroRecord[] {
  return snapshot.heroes.map((hero) => {
    const tactics = HERO_TACTICS[hero.name] ?? synthesizeFallbackHeroTactics(hero);
    return {
      ...hero,
      ...tactics,
    };
  });
}
